"""Stage the TRS-80 boot assets into a fujinet-nio checkout so `./build.sh -f` packs them into the board's flash.

  tools/stage_fujinet_flash.py --nio-repo ~/dev/fujinet-nio-workspace/repos/fujinet-nio [--config]

Writes, under <nio>/distfiles/esp32-data/ (generated files; not committed there):
  boot/trs80/nioboot.cmd   the ROM-loader load module (build/nioboot.cmd; with --config build/nioboot-config.cmd, which starts CONFIG/CMD; boot.dsk must then contain it)
  boot/trs80/boot.xfd      images/boot.dsk as a raw 256-byte-sector image (180 KB, 720 sectors)
  fujinet.yaml             19200 8O1, boot disk and loader on flash:, TRS-80 loader sender on
Build first: `make` and `python3 tools/make_boot_image.py --base images/lsdos631l-upstream/L631NEW.DSK --out images/boot.dsk`.
Then set `boot_images = trs80` in the nio checkout's platformio.local.ini ([fujinet] section).
"""
import argparse, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from tools.make_nio_images import flat  # noqa: E402

YAML = """\
# Generated by tools/stage_fujinet_flash.py in boot-trs80-4p: the RS-232 board as the 4P's FujiNet.
boot:
  mode: config
  config_uri: flash:/boot/trs80/boot.xfd
  readonly: false
clock:
  timezone: EST5EDT,M3.2.0,M11.1.0   # a POSIX TZ string: the ESP32 has no zoneinfo database
  enabled: true
wifi:
  enabled: false
channel:
  uart:
    baud_rate: 19200
    data_bits: 8
    parity: odd
    stop_bits: 1
    flow_control: none
    tx_chunk_size: 16
    tx_chunk_gap_us: 2000
trs80_loader:
  enabled: true
  path: flash:/boot/trs80/nioboot.cmd
  probe_interval_ms: 100
  idle_seconds: 10
"""


def stage(nio_repo, autostart=False, root=ROOT):
    data = os.path.join(os.path.expanduser(nio_repo), "distfiles", "esp32-data")
    boot = os.path.join(data, "boot", "trs80")
    os.makedirs(boot, exist_ok=True)
    cmd_src = os.path.join(root, "build", "nioboot-config.cmd" if autostart else "nioboot.cmd")
    for need in (cmd_src, os.path.join(root, "images", "boot.dsk")):
        if not os.path.isfile(need):
            sys.exit(f"missing {need} (see the build steps in this script's help)")
    with open(cmd_src, "rb") as f, open(os.path.join(boot, "nioboot.cmd"), "wb") as o:
        o.write(f.read())
    with open(os.path.join(boot, "boot.xfd"), "wb") as o:
        o.write(flat(os.path.join(root, "images", "boot.dsk")))
    with open(os.path.join(data, "fujinet.yaml"), "w") as o:
        o.write(YAML)
    return sorted(os.path.join(dp, n)[len(data) + 1:] for dp, _, ns in os.walk(data) for n in ns if "trs80" in dp or n == "fujinet.yaml")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--nio-repo", required=True)
    ap.add_argument("--config", action="store_true", help="autostart CONFIG after LS-DOS boots (images/boot.dsk must include CONFIG/CMD)")
    a = ap.parse_args()
    for p in stage(a.nio_repo, a.config):
        print("staged", p)


if __name__ == "__main__":
    main()
